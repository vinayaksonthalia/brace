// TestNoDangerousStatementIsCalledSafe is the FIX #4 adversarial table: a single
// false-"safe" on a dangerous migration is a credibility-killer, so every shape
// that takes a table-rewriting or ACCESS EXCLUSIVE-and-scanning lock must come
// back predictedSafe=false AND triviallySafe=false. It is the negative twin of
// TestSafeDetector, aimed squarely at the shapes most likely to slip through:
// SERIAL / IDENTITY / GENERATED columns, which carry an implicit volatile
// default and used to be mislabelled add_column_const_default (already_safe).
func TestNoDangerousStatementIsCalledSafe(t *testing.T) {
	dangerous := []string{
		// index builds under a blocking lock
		`CREATE INDEX idx ON orders (customer_id)`,
		`CREATE UNIQUE INDEX idx ON orders (customer_id)`,
		`DROP INDEX idx`,
		`REINDEX INDEX idx`,
		`REINDEX TABLE orders`,
		// column type change: rewrite
		`ALTER TABLE orders ALTER COLUMN amount_cents TYPE numeric`,
		`ALTER TABLE orders ALTER COLUMN amount_cents SET DATA TYPE bigint`,
		// volatile / rewriting ADD COLUMN forms
		`ALTER TABLE orders ADD COLUMN created timestamptz DEFAULT now()`,
		`ALTER TABLE orders ADD COLUMN r double precision DEFAULT random()`,
		`ALTER TABLE orders ADD COLUMN u uuid DEFAULT gen_random_uuid()`,
		`ALTER TABLE orders ADD COLUMN n bigint DEFAULT nextval('s')`,
		// the shapes FIX #4 added: implicit volatile default / per-row compute
		`ALTER TABLE orders ADD COLUMN sid serial`,
		`ALTER TABLE orders ADD COLUMN sid bigserial`,
		`ALTER TABLE orders ADD COLUMN sid smallserial`,
		`ALTER TABLE orders ADD COLUMN sid int GENERATED ALWAYS AS IDENTITY`,
		`ALTER TABLE orders ADD COLUMN sid int GENERATED BY DEFAULT AS IDENTITY`,
		`ALTER TABLE orders ADD COLUMN doubled bigint GENERATED ALWAYS AS (amount_cents * 2) STORED`,
		// constraints validated in place under ACCESS EXCLUSIVE
		`ALTER TABLE orders ADD CONSTRAINT chk CHECK (amount_cents > 0)`,
		`ALTER TABLE orders ADD CONSTRAINT fk FOREIGN KEY (customer_id) REFERENCES customers (id)`,
		`ALTER TABLE orders ADD COLUMN sku text UNIQUE`,
		`ALTER TABLE orders ADD PRIMARY KEY (id)`,
		// scan-the-whole-table forms
		`ALTER TABLE orders ALTER COLUMN customer_id SET NOT NULL`,
		`VACUUM FULL orders`,
	}
	for _, sql := range dangerous {
		t.Run("dangerous/"+sql[:min(len(sql), 52)], func(t *testing.T) {
			as, err := Assess(sql)
			// Some dangerous shapes are still accepted for a run (err == nil); the
			// only thing forbidden is calling them safe. If the pre-filter ever
			// answered one of these already_safe, that IS the bug — catch both the
			// RejectAlreadySafe path and the predicted/trivially-safe flags.
			var rej *RejectedError
			if errors.As(err, &rej) && rej.Kind == RejectAlreadySafe {
				t.Fatalf("FALSE-SAFE: %q was answered already_safe (class %s) — a dangerous statement must never be waved through",
					sql, rej.Classification)
			}
			if as == nil {
				t.Fatalf("Assess(%q) returned no assessment (err=%v)", sql, err)
			}
			if as.PredictedSafe {
				t.Errorf("FALSE-SAFE: %q predictedSafe=true (class %s)", sql, as.Classification)
			}
			if as.Lesson.TriviallySafe {
				t.Errorf("FALSE-SAFE: %q triviallySafe=true (class %s)", sql, as.Classification)
			}
			if as.Lesson.BlocksWrites != true {
				t.Errorf("%q classified as not blocking writes (class %s) — expected a blocking shape", sql, as.Classification)
			}
		})
	}
}

// TestAlreadySafeAccessExclusiveCarriesAcquisitionQualifier pins BUG A: an
// already_safe shape that still takes ACCESS EXCLUSIVE (metadata-only ADD COLUMN
// with a constant default) is safe about the WORK but not about the WAIT. It gets
// the lock instantly on an idle twin, but in production it queues behind the
// longest open transaction and everything queues behind it. The already_safe
// rejection must therefore carry qualifier "acquisition_not_simulated" and a note
// pointing at hostile mode — an unqualified SAFE would let a CI gate ship a change
// that freezes writes the moment it queues. A shape whose lock blocks nobody
// (COMMENT, ANALYZE) must NOT carry the qualifier.
func TestAlreadySafeAccessExclusiveCarriesAcquisitionQualifier(t *testing.T) {
	accessExclusive := []string{
		`ALTER TABLE orders ADD COLUMN promo int`,
		`ALTER TABLE orders ADD COLUMN notes text`,
		`ALTER TABLE orders ADD COLUMN status text DEFAULT 'new'`,
		`ALTER TABLE orders ADD COLUMN n int NOT NULL DEFAULT 0`,
	}
	for _, sql := range accessExclusive {
		t.Run("access_exclusive/"+sql[:min(len(sql), 48)], func(t *testing.T) {
			_, err := Assess(sql)
			var rej *RejectedError
			if !errors.As(err, &rej) || rej.Kind != RejectAlreadySafe {
				t.Fatalf("Assess(%q) = %v, want an already_safe rejection", sql, err)
			}
			if rej.Classification != ClassAddColumnConstDefault {
				t.Fatalf("classification = %q, want %q", rej.Classification, ClassAddColumnConstDefault)
			}
			// The heart of the fix: never a bare, unconditional SAFE.
			if rej.Qualifier != QualifierAcquisitionNotSimulated {
				t.Errorf("qualifier = %q, want %q — an ACCESS EXCLUSIVE already_safe shape must flag the untested wait",
					rej.Qualifier, QualifierAcquisitionNotSimulated)
			}
			if rej.Note == "" {
				t.Error("no note: the caller must be told the acquisition wait was not simulated")
			}
			for _, want := range []string{"ACCESS EXCLUSIVE", "hostile"} {
				if !strings.Contains(rej.Note, want) {
					t.Errorf("note missing %q:\n%s", want, rej.Note)
				}
			}
		})
	}

	// The control: a shape whose lock blocks nobody must NOT carry the qualifier —
	// there is no acquisition freeze to warn about.
	harmless := []string{
		`ANALYZE orders`,
		`COMMENT ON TABLE orders IS 'the orders table'`,
	}
	for _, sql := range harmless {
		t.Run("harmless/"+sql[:min(len(sql), 48)], func(t *testing.T) {
			_, err := Assess(sql)
			var rej *RejectedError
			if !errors.As(err, &rej) || rej.Kind != RejectAlreadySafe {
				t.Fatalf("Assess(%q) = %v, want an already_safe rejection", sql, err)
			}
			if rej.Qualifier != "" {
				t.Errorf("qualifier = %q on a non-ACCESS-EXCLUSIVE shape; want none (lock %q)",
					rej.Qualifier, rej.Classification)
			}
			if rej.Note != "" {
				t.Errorf("note = %q on a harmless shape; want none", rej.Note)
			}
		})
	}
}

// TestGenuinelySafeStatementsAreCalledSafe is the positive control: the shapes
// that really do keep writes flowing must be recognised as safe, or Brace would
// nag users into rewrites they do not need.
func TestGenuinelySafeStatementsAreCalledSafe(t *testing.T) {
	safe := []struct {
		sql           string
		triviallySafe bool // true = answered already_safe (no run); false = predictedSafe run
	}{
		{`CREATE INDEX CONCURRENTLY idx ON orders (customer_id)`, false},
		{`CREATE UNIQUE INDEX CONCURRENTLY idx ON orders (customer_id)`, false},
		{`DROP INDEX CONCURRENTLY idx`, false},
		{`REINDEX INDEX CONCURRENTLY idx`, false},
		{`ALTER TABLE orders ADD COLUMN notes text`, true},
		{`ALTER TABLE orders ADD COLUMN status text DEFAULT 'new'`, true},
		{`ALTER TABLE orders ADD COLUMN n int NOT NULL DEFAULT 0`, true},
		{`ALTER TABLE orders ADD CONSTRAINT fk FOREIGN KEY (customer_id) REFERENCES customers (id) NOT VALID`, false},
		{`ALTER TABLE orders VALIDATE CONSTRAINT fk`, false},
		{`VACUUM (ANALYZE) orders`, false},
		{`ANALYZE orders`, true},
		{`COMMENT ON TABLE orders IS 'the orders table'`, true},
	}
	for _, c := range safe {
		t.Run("safe/"+c.sql[:min(len(c.sql), 52)], func(t *testing.T) {
			as, err := Assess(c.sql)
			if as == nil {
				t.Fatalf("Assess(%q) returned no assessment (err=%v)", c.sql, err)
			}
			if !as.PredictedSafe {
				t.Errorf("%q predictedSafe=false — a genuinely safe shape must be recognised", c.sql)
			}
			if c.triviallySafe {
				var rej *RejectedError
				if !errors.As(err, &rej) || rej.Kind != RejectAlreadySafe {
					t.Errorf("%q should be answered already_safe, got err=%v", c.sql, err)
				}
			} else if err != nil {
				t.Errorf("%q should be accepted for a run, got err=%v", c.sql, err)
			}
		})
	}
}
